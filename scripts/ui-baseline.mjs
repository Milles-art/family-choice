import { createRequire } from 'node:module';
import fs from 'node:fs';
const require=createRequire(import.meta.url);
const { chromium } = require('C:/Users/DIGITAL STAR/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
console.log('Browser launched');
const products=JSON.parse(fs.readFileSync('backend/database/seeders/data/products.json','utf8')).map(p=>({...p,stock:100,inStock:true}));
const settings={currency:'TZS',tax_rate:.18,delivery_cents:500000,free_delivery_cents:7500000,mobile_money_enabled:false};
fs.mkdirSync('artifacts/ui',{recursive:true});
fs.writeFileSync('artifacts/ui/catalog-snapshot.json',JSON.stringify(products,null,2));
await context.route('**/api/**',route=> { const path=new URL(route.request().url()).pathname; return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(path==='/api/products'?products:path==='/api/settings'?settings:{})}); });
const page=await context.newPage();
await page.addInitScript(()=>{window.lab={cls:0,lcp:0}; new PerformanceObserver(list=>{for(const e of list.getEntries())if(!e.hadRecentInput)window.lab.cls+=e.value}).observe({type:'layout-shift',buffered:true});new PerformanceObserver(list=>{window.lab.lcp=list.getEntries().at(-1).startTime}).observe({type:'largest-contentful-paint',buffered:true});});
await page.goto('http://127.0.0.1:4173');await page.getByRole('heading',{name:'Shop by Category'}).waitFor();await page.waitForTimeout(5000);
const result=await page.evaluate(()=>({...window.lab,navigation:performance.getEntriesByType('navigation')[0].toJSON(),transferredBytes:performance.getEntriesByType('resource').reduce((sum,e)=>sum+e.transferSize,0)}));
fs.writeFileSync('artifacts/ui/baseline-lab.json',JSON.stringify(result,null,2));
await page.screenshot({path:'artifacts/ui/baseline-desktop.png',fullPage:true});
console.log(JSON.stringify({products:products.length,lab:result}));
await browser.close();
